"""Deduplicates recognized books and writes books.yaml."""

from pathlib import Path

import yaml

from shelf.text import THRESHOLD, similarity

FIELDS = ("title", "authors", "known_as", "read_as", "source", "photo", "work", "cover_id", "cover_url")
HEADER = "# Books recognized in your shelf photos, generated by `shelf`.\n\n"


def dedupe(books: list[dict]) -> list[dict]:
    """Merges the same book seen in overlapping photos."""
    unique: list[dict] = []
    for book in books:
        for seen in unique:
            score = similarity(book["title"], seen["title"])
            same_work = book.get("work") and book.get("work") == seen.get("work")
            if score >= THRESHOLD or (same_work and score >= 0.6):
                if not seen.get("authors") and book.get("authors"):
                    seen["authors"] = book["authors"]
                break
        else:
            unique.append(dict(book))
    return unique


def write_books_yaml(path: Path, books: list[dict], left_out: list[dict] | None = None) -> None:
    """`read_as` keeps what the photo said when the title changed; `source` says where the title came from."""
    data = {"books": [{k: b[k] for k in FIELDS if b.get(k) not in (None, [], "")} for b in books]}
    if left_out:
        data["left_out"] = left_out
    path.write_text(
        HEADER + yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=100),
        encoding="utf-8",
    )
